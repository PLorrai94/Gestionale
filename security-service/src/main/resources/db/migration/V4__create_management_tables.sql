-- V4: Crea le tabelle per il management-service (Customer, Product, Orders, OrderItem)

CREATE TABLE CUSTOMER (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(100 CHAR) NOT NULL,
    LAST_NAME  VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(100 CHAR) UNIQUE NOT NULL,
    PHONE_NUMBER VARCHAR2(30 CHAR)
);

CREATE TABLE PRODUCT (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    PRICE NUMBER(10, 2) NOT NULL,
    STOCK_QUANTITY NUMBER DEFAULT 0
);

CREATE TABLE ORDERS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    ORDER_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR2(50 CHAR),
    CONSTRAINT FK_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(ID)
);

CREATE TABLE ORDER_ITEM (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER NOT NULL,
    PRICE NUMBER(10, 2) NOT NULL,
    CONSTRAINT FK_ORDERITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID),
    CONSTRAINT FK_ORDERITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(ID)
);